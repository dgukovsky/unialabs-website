const email = String.fromCharCode(104, 101, 108, 108, 111, 64, 117, 110, 105, 97, 108, 97, 98, 115, 46, 99, 111, 109);
const languageButtons = [...document.querySelectorAll("[data-lang]")];

const setLanguage = (language) => {
  const lang = translations[language] ? language : "es";
  const dictionary = translations[lang];

  document.documentElement.lang = lang;
  document.title = dictionary.pageTitle;
  document.querySelector('meta[name="description"]')?.setAttribute("content", dictionary.pageDescription);
  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const value = dictionary[element.dataset.i18n];
    if (value) element.textContent = value;
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
    const value = dictionary[element.dataset.i18nPlaceholder];
    if (value) element.placeholder = value;
  });
  languageButtons.forEach((button) => {
    const isActive = button.dataset.lang === lang;
    button.classList.toggle("is-active", isActive);
    button.setAttribute("aria-pressed", String(isActive));
  });
  localStorage.setItem("unia-pilot-language", lang);
};

const queryLanguage = new URLSearchParams(window.location.search).get("lang");
const initialLanguage = queryLanguage || localStorage.getItem("unia-pilot-language") || "es";
setLanguage(initialLanguage);

languageButtons.forEach((button) => button.addEventListener("click", () => setLanguage(button.dataset.lang)));

document.querySelectorAll("[data-year]").forEach((element) => {
  element.textContent = new Date().getFullYear();
});

document.querySelectorAll("[data-email-text]").forEach((element) => {
  element.textContent = email;
  element.closest("a")?.setAttribute("href", `mailto:${email}`);
});

document.querySelectorAll('.pilot-socials a[aria-label="Email"]').forEach((element) => {
  element.setAttribute("href", `mailto:${email}`);
});

document.querySelector("[data-pilot-form]")?.addEventListener("submit", (event) => {
  event.preventDefault();
  const form = event.currentTarget;
  if (!form.reportValidity()) return;

  const values = Object.fromEntries(new FormData(form));
  const language = document.documentElement.lang;
  const subject = language === "en"
    ? `UNIA Labs pilot request - ${values.company}`
    : `Solicitud programa piloto UNIA Labs - ${values.company}`;
  const labels = language === "en"
    ? ["Name", "Company", "Email", "WhatsApp", "Process", "Current workflow", "Business impact"]
    : ["Nombre", "Empresa", "Correo", "WhatsApp", "Proceso", "Gestión actual", "Impacto en el negocio"];
  const body = [values.name, values.company, values.email, values.whatsapp || "-", values.process, values.current, values.impact]
    .map((value, index) => `${labels[index]}: ${value}`)
    .join("\n\n");

  window.location.href = `mailto:${email}?subject=${encodeURIComponent(subject)}&body=${encodeURIComponent(body)}`;
});
