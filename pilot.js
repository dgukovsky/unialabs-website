const email = String.fromCharCode(104, 101, 108, 108, 111, 64, 117, 110, 105, 97, 108, 97, 98, 115, 46, 99, 111, 109);
const languageButtons = [...document.querySelectorAll("[data-lang]")];

const setLanguage = (language) => {
  const lang = translations[language] ? language : "es";
  const dictionary = translations[lang];

  document.documentElement.lang = lang;
  document.title = dictionary.pageTitle;
  document.querySelector('meta[name="description"]')?.setAttribute("content", dictionary.pageDescription);
  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const value = dictionary[element.dataset.i18n];
    if (value) element.textContent = value;
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
    const value = dictionary[element.dataset.i18nPlaceholder];
    if (value) element.placeholder = value;
  });
  document.querySelectorAll("[data-i18n-aria-label]").forEach((element) => {
    const value = dictionary[element.dataset.i18nAriaLabel];
    if (value) element.setAttribute("aria-label", value);
  });
  languageButtons.forEach((button) => {
    const isActive = button.dataset.lang === lang;
    button.classList.toggle("is-active", isActive);
    button.setAttribute("aria-pressed", String(isActive));
  });
  localStorage.setItem("unia-pilot-language", lang);
};

const queryLanguage = new URLSearchParams(window.location.search).get("lang");
const initialLanguage = queryLanguage || localStorage.getItem("unia-pilot-language") || "es";
setLanguage(initialLanguage);

languageButtons.forEach((button) => button.addEventListener("click", () => setLanguage(button.dataset.lang)));

document.querySelectorAll("[data-year]").forEach((element) => {
  element.textContent = new Date().getFullYear();
});

document.querySelectorAll("[data-email-text]").forEach((element) => {
  element.textContent = email;
  element.closest("a")?.setAttribute("href", `mailto:${email}`);
});

document.querySelectorAll('.pilot-socials a[aria-label="Email"]').forEach((element) => {
  element.setAttribute("href", `mailto:${email}`);
});

const meetingModal = document.querySelector("[data-meeting-modal]");
const meetingTriggers = [...document.querySelectorAll("[data-meeting-trigger]")];
let lastMeetingTrigger = null;
let meetingCloseTimer = null;

const getMeetingFocusableElements = () => meetingModal
  ? [...meetingModal.querySelectorAll('button:not([disabled]), a[href]')]
  : [];

const openMeetingModal = (trigger) => {
  if (!meetingModal) return;
  window.clearTimeout(meetingCloseTimer);
  lastMeetingTrigger = trigger;
  meetingModal.hidden = false;
  document.body.classList.add("is-meeting-modal-open");
  window.requestAnimationFrame(() => {
    meetingModal.classList.add("is-open");
    getMeetingFocusableElements()[0]?.focus();
  });
};

const closeMeetingModal = () => {
  if (!meetingModal || meetingModal.hidden) return;
  meetingModal.classList.remove("is-open");
  document.body.classList.remove("is-meeting-modal-open");
  const finishClose = () => {
    meetingModal.hidden = true;
    lastMeetingTrigger?.focus();
  };
  if (window.matchMedia("(prefers-reduced-motion: reduce)").matches) {
    finishClose();
  } else {
    meetingCloseTimer = window.setTimeout(finishClose, 420);
  }
};

meetingTriggers.forEach((trigger) => {
  trigger.addEventListener("click", () => openMeetingModal(trigger));
});

meetingModal?.querySelectorAll("[data-meeting-close]").forEach((element) => {
  element.addEventListener("click", closeMeetingModal);
});

meetingModal?.querySelectorAll(".pilot-meeting-option").forEach((option) => {
  option.addEventListener("click", closeMeetingModal);
});

document.addEventListener("keydown", (event) => {
  if (!meetingModal || meetingModal.hidden) return;
  if (event.key === "Escape") {
    event.preventDefault();
    closeMeetingModal();
    return;
  }
  if (event.key !== "Tab") return;

  const focusableElements = getMeetingFocusableElements();
  const firstElement = focusableElements[0];
  const lastElement = focusableElements.at(-1);
  if (event.shiftKey && document.activeElement === firstElement) {
    event.preventDefault();
    lastElement?.focus();
  } else if (!event.shiftKey && document.activeElement === lastElement) {
    event.preventDefault();
    firstElement?.focus();
  }
});

document.querySelector("[data-pilot-form]")?.addEventListener("submit", (event) => {
  event.preventDefault();
  const form = event.currentTarget;
  if (!form.reportValidity()) return;

  const values = Object.fromEntries(new FormData(form));
  const language = document.documentElement.lang;
  const subject = language === "en"
    ? `UNIA Labs pilot request - ${values.company}`
    : `Solicitud programa piloto UNIA Labs - ${values.company}`;
  const labels = language === "en"
    ? ["Name", "Company", "Email", "WhatsApp", "Process", "Current workflow", "Business impact"]
    : ["Nombre", "Empresa", "Correo", "WhatsApp", "Proceso", "Gestión actual", "Impacto en el negocio"];
  const body = [values.name, values.company, values.email, values.whatsapp || "-", values.process, values.current, values.impact]
    .map((value, index) => `${labels[index]}: ${value}`)
    .join("\n\n");

  window.location.href = `mailto:${email}?subject=${encodeURIComponent(subject)}&body=${encodeURIComponent(body)}`;
});

const reducedMotion = window.matchMedia("(prefers-reduced-motion: reduce)").matches;

if (!reducedMotion) {
  document.documentElement.classList.add("pilot-motion-ready");

  const revealSelectors = [
    ".pilot-section .pilot-kicker",
    ".pilot-section h2",
    ".pilot-step",
    ".pilot-note",
    ".pilot-included-grid article",
    ".pilot-disclaimer",
    ".pilot-examples-grid article",
    ".pilot-apply-copy > *",
    ".pilot-form",
    ".pilot-footer-inner > div",
    ".pilot-footer-bottom",
  ];
  const revealTargets = [];

  revealSelectors.forEach((selector) => {
    document.querySelectorAll(selector).forEach((element, index) => {
      element.classList.add("pilot-reveal");
      element.style.setProperty("--pilot-reveal-delay", `${Math.min(index, 7) * 65}ms`);
      revealTargets.push(element);
    });
  });

  if ("IntersectionObserver" in window) {
    const revealObserver = new IntersectionObserver((entries) => {
      entries.forEach((entry) => {
        if (!entry.isIntersecting) return;
        entry.target.classList.add("is-visible");
        revealObserver.unobserve(entry.target);
      });
    }, { rootMargin: "0px 0px -8%", threshold: 0.12 });

    revealTargets.forEach((element) => revealObserver.observe(element));
  } else {
    revealTargets.forEach((element) => element.classList.add("is-visible"));
  }

  const hero = document.querySelector(".pilot-hero");
  const dashboard = document.querySelector(".pilot-dashboard-wrap");
  const precisePointer = window.matchMedia("(hover: hover) and (pointer: fine)").matches;

  if (hero && dashboard && precisePointer) {
    hero.addEventListener("pointermove", (event) => {
      const bounds = hero.getBoundingClientRect();
      const horizontal = (event.clientX - bounds.left) / bounds.width - 0.5;
      const vertical = (event.clientY - bounds.top) / bounds.height - 0.5;
      dashboard.style.setProperty("--pilot-tilt-x", `${vertical * -3.5}deg`);
      dashboard.style.setProperty("--pilot-tilt-y", `${horizontal * 4.5}deg`);
    }, { passive: true });

    hero.addEventListener("pointerleave", () => {
      dashboard.style.setProperty("--pilot-tilt-x", "0deg");
      dashboard.style.setProperty("--pilot-tilt-y", "0deg");
    });
  }
}
